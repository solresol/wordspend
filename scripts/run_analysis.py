#!/usr/bin/env python3
"""Run wordspend residual analysis from CSV or PostgreSQL."""

from __future__ import annotations

import argparse
import json
import subprocess
from pathlib import Path

import pandas as pd

from wordspend.analysis import analyze_translation_spend, write_analysis_outputs
from wordspend.db import connect, fetch_segments, save_analysis_result, stable_hash
from wordspend.eligibility import select_analysis_segments


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", help="CSV with source_text and target_text columns.")
    parser.add_argument("--from-db", action="store_true", help="Read aligned segments from PostgreSQL.")
    parser.add_argument("--work", action="append", dest="works", help="Restrict to a work slug. Repeatable.")
    parser.add_argument("--limit", type=int, default=0)
    parser.add_argument("--metric", default="tokens", choices=["tokens", "characters", "syllables"])
    parser.add_argument("--baseline", default="log", choices=["log", "linear"])
    parser.add_argument("--min-df", type=int, default=2)
    parser.add_argument("--top-n", type=int, default=40)
    parser.add_argument("--max-features", type=int, default=2000)
    parser.add_argument("--corpus-label", default="all")
    parser.add_argument("--output-dir", default="build/analysis")
    parser.add_argument("--save-db", action="store_true")
    parser.add_argument('--mode', choices=['paper', 'bootstrap'], default='paper')
    args = parser.parse_args()
    if bool(args.from_db) == bool(args.input):
        parser.error('Choose exactly one of --from-db or --input')
    if args.save_db and not args.from_db:
        parser.error('--save-db requires --from-db; CSV IDs are not database identities')

    if args.from_db:
        with connect() as conn:
            frame = fetch_segments(conn, work_slugs=args.works, limit=args.limit if args.limit > 0 else None, mode=args.mode)
    elif args.input:
        frame = pd.read_csv(args.input)
        if args.limit and args.limit > 0:
            frame = frame.head(args.limit)
    else:
        raise SystemExit("Use --from-db or --input.")

    result = analyze_translation_spend(
        frame,
        metric=args.metric,
        baseline=args.baseline,
        min_df=args.min_df,
        top_n=args.top_n,
        max_features=args.max_features,
        corpus_label=args.corpus_label,
        analysis_mode=args.mode,
    )
    if not result["available"]:
        raise SystemExit(result["message"])

    repo = Path(__file__).resolve().parents[1]
    revision = subprocess.check_output(['git', '-C', str(repo), 'rev-parse', 'HEAD'], text=True).strip()
    result['metrics']['source_revision'] = revision
    parameters = dict(vars(args))
    for key in ['output_dir', 'save_db']:
        parameters.pop(key)
    result['metrics']['run_key'] = stable_hash(
        select_analysis_segments(frame, args.mode).to_json(orient='records', force_ascii=False),
        json.dumps(parameters, sort_keys=True), revision)

    if args.save_db:
        with connect() as conn:
            run_id = save_analysis_result(conn, result, notes=f"Generated by scripts/run_analysis.py into {args.output_dir}")
        print(f"Saved analysis_run_id={run_id}")
        result['metrics']['analysis_run_id'] = run_id
    output_dir = Path(args.output_dir)
    write_analysis_outputs(result, output_dir)
    print(f"Wrote {args.mode} analysis outputs to {output_dir}")


if __name__ == "__main__":
    main()
